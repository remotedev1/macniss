import { test, expect } from "@playwright/test";
import { loginAsCmsUser } from "../helpers/auth";

const destructive =
  process.env.E2E_ALLOW_DESTRUCTIVE === "true" &&
  process.env.E2E_DATABASE_ISOLATED === "true";

test.describe("isolated CMS CRUD", () => {
  test.skip(!destructive, "Set E2E_ALLOW_DESTRUCTIVE=true and E2E_DATABASE_ISOLATED=true only for a disposable test database.");

  test.beforeEach(async ({ page }) => {
    await loginAsCmsUser(page);
  });

  test("project create, update, archive, unarchive and delete", async ({ page }) => {
    const stamp = Date.now();
    const create = await page.request.post("/api/projects", {
      multipart: {
        projectName: `E2E Project ${stamp}`,
        projectTagline: "Automated release verification",
        projectType: "RESIDENTIAL",
        clientName: "E2E Client",
        contractorName: "Macniss",
        architectName: "E2E Architect",
        location: "Bengaluru",
        startDate: "2026-01-15",
        completionDate: "2027-01-15",
        estimatedCost: "15000000",
        status: "ACTIVE",
        overview: "Disposable project generated by isolated E2E testing.",
        objectives: JSON.stringify(["Verify CRUD integrity"]),
        keyFeatures: JSON.stringify([{ title: "QA", description: "Disposable automated verification" }]),
        technologiesUsed: JSON.stringify(["E2E"]),
        youtubeLinks: JSON.stringify([]),
        instagramLinks: JSON.stringify([]),
      },
    });
    expect(create.status()).toBe(201);
    const project = await create.json();
    expect(project.projectTagline).toBe("Automated release verification");
    expect(project.estimatedCost).toBe(15000000);

    const update = await page.request.put(`/api/projects/${project.id}`, {
      multipart: {
        projectName: `E2E Project Updated ${stamp}`,
        projectTagline: "Updated automated verification",
        projectType: "COMMERCIAL",
        clientName: "E2E Client",
        contractorName: "Macniss",
        architectName: "E2E Architect",
        location: "Mysuru",
        startDate: "2026-02-01",
        completionDate: "2027-02-01",
        estimatedCost: "17500000",
        status: "ACTIVE",
        overview: "Updated disposable project.",
        objectives: JSON.stringify(["Verify update integrity"]),
        keyFeatures: JSON.stringify([{ title: "Updated QA", description: "Update path verified" }]),
        technologiesUsed: JSON.stringify(["Playwright"]),
        youtubeLinks: JSON.stringify([]),
        instagramLinks: JSON.stringify([]),
        deletedFileIds: JSON.stringify([]),
      },
    });
    expect(update.ok()).toBeTruthy();
    expect((await update.json()).location).toBe("Mysuru");

    const archive = await page.request.patch(`/api/projects/${project.id}/archive`, {
      data: { isArchived: true },
    });
    expect(archive.ok()).toBeTruthy();
    expect((await archive.json()).isArchived).toBe(true);

    const unarchive = await page.request.patch(`/api/projects/${project.id}/archive`, {
      data: { isArchived: false },
    });
    expect(unarchive.ok()).toBeTruthy();
    expect((await unarchive.json()).isArchived).toBe(false);

    const remove = await page.request.delete(`/api/projects/${project.id}`);
    expect(remove.ok()).toBeTruthy();
  });

  test("capability create, archive, unarchive and delete", async ({ page }) => {
    const stamp = Date.now();
    const create = await page.request.post("/api/solutions", {
      multipart: {
        title: `E2E Capability ${stamp}`,
        description: "Disposable capability created by QA.",
        isArchived: "false",
      },
    });
    expect(create.status()).toBe(201);
    const capability = await create.json();
    expect(Array.isArray(capability.image)).toBe(true);

    const archive = await page.request.patch(`/api/solutions/${capability.id}`, {
      data: { isArchived: true },
    });
    expect(archive.ok()).toBeTruthy();
    expect((await archive.json()).isArchived).toBe(true);

    const unarchive = await page.request.patch(`/api/solutions/${capability.id}`, {
      data: { isArchived: false, title: `E2E Capability Updated ${stamp}` },
    });
    expect(unarchive.ok()).toBeTruthy();

    const remove = await page.request.delete(`/api/solutions/${capability.id}`);
    expect(remove.ok()).toBeTruthy();
  });

  test("testimonial create, update and archive", async ({ page }) => {
    const stamp = Date.now();
    const create = await page.request.post("/api/testimonials", {
      data: {
        name: `E2E Client ${stamp}`,
        role: "QA",
        image: "",
        quote: "Disposable release-candidate testimonial.",
        isArchived: false,
      },
    });
    expect(create.status()).toBe(201);
    const body = await create.json();
    const testimonial = body.data;

    const update = await page.request.patch(`/api/testimonials/${testimonial.id}`, {
      data: { quote: "Updated disposable testimonial." },
    });
    expect(update.ok()).toBeTruthy();
    expect((await update.json()).quote).toContain("Updated");

    const archive = await page.request.delete(`/api/testimonials/${testimonial.id}`);
    expect(archive.ok()).toBeTruthy();
    expect((await archive.json()).isArchived).toBe(true);
  });

  test("consultation creation and CMS status workflow", async ({ page }) => {
    const stamp = Date.now();
    const create = await page.request.post("/api/consultations", {
      data: {
        name: `E2E Enquiry ${stamp}`,
        email: `e2e-${stamp}@example.com`,
        phone: "9876543210",
        state: "Karnataka",
        details: "Disposable enquiry for release QA.",
      },
    });
    expect(create.status()).toBe(201);
    const enquiry = (await create.json()).data;

    const update = await page.request.patch(`/api/consultations/${enquiry.id}`, {
      data: { status: "CONTACTED" },
    });
    expect(update.ok()).toBeTruthy();
    const updated = await update.json();
    expect(updated.data.status).toBe("CONTACTED");
  });

  test("invalid image MIME type is rejected before ImageKit upload", async ({ page }) => {
    const response = await page.request.post("/api/solutions", {
      multipart: {
        title: "Invalid image QA",
        description: "Should not be created.",
        image: {
          name: "not-an-image.txt",
          mimeType: "text/plain",
          buffer: Buffer.from("not an image"),
        },
      },
    });
    expect(response.status()).toBe(400);
  });
});
